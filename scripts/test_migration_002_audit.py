PASS = 0
FAIL: list[str] = []


def check(name: str, cond: bool) -> None:
    global PASS
    if cond:
        PASS += 1
        print(f"  ok - {name}")
    else:
        FAIL.append(name)
        print(f"  FAIL - {name}")


def _strip_sql_comments(sql: str) -> str:
    """라인 주석(--)을 제거해 '실행되는' DDL 만 남긴다(롤백 안내 주석 배제)."""
    out = []
    for line in sql.splitlines():
        idx = line.find("--")
        out.append(line if idx < 0 else line[:idx])
    return "\n".join(out)


MIG = ROOT / "supabase" / "migrations"
SQL1 = (MIG / "001_initial_schema.sql").read_text(encoding="utf-8")
SQL2 = (MIG / "002_schedule_assignments.sql").read_text(encoding="utf-8")
EXEC1 = _strip_sql_comments(SQL1).lower()
EXEC2 = _strip_sql_comments(SQL2).lower()
DATA_TABLES = ("departments", "teams", "users", "work_types", "work_schedules")


# ===== 1) 정적 SQL 불변식 =====
