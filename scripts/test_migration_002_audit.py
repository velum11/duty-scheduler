# 실행 구문에 기존 데이터 테이블을 drop 하는 문장이 없어야 한다(롤백은 주석 안내뿐).
active_drop = any(re.search(rf"drop\s+table\s+(if\s+exists\s+)?(public\.)?{t}\b", EXEC1 + EXEC2)
                  for t in DATA_TABLES)
check("실행 DDL 에 기존 데이터 테이블 DROP 없음(롤백은 주석뿐)", not active_drop)

check("002: schedule_assignments 를 create table if not exists 로 생성",
      "create table if not exists public.schedule_assignments" in EXEC2)
check("002: shift_groups 를 create table if not exists 로 생성",
      "create table if not exists public.shift_groups" in EXEC2)
check("002: work_schedules 는 add column if not exists 만(파괴적 변경 없음)",
      "add column if not exists schedule_assignment_id" in EXEC2
      and "drop column" not in EXEC2 and "alter column" not in EXEC2)

check("002: 직원-월 UNIQUE(user_id, schedule_month)",
      "unique (user_id, schedule_month)" in EXEC2)
check("002: schedule_month 는 월 1일 CHECK",
      "extract(day from schedule_month) = 1" in EXEC2)
check("002: team 은 (team_id, department_id) 복합 FK(teams 소속 보장)",
      "foreign key (team_id, department_id)" in EXEC2
      and "references public.teams(id, department_id)" in EXEC2)
# 스냅샷 무결성: shift_group_code 는 shift_groups 로의 FK 가 아니어야 한다.
check("002: shift_group_code 는 shift_groups FK 아님(기준정보 변경이 과거를 깨지 않음)",
      "references public.shift_groups" not in EXEC2)
check("002: shift_group_code NULL 허용(현재 편성 화면은 근무조 미입력)",
      "shift_group_code text," in EXEC2 and "shift_group_code text not null" not in EXEC2)

# *** 핵심 계약: 002 는 DDL 전용 — 데이터 조작(DML)이 전혀 없어야 한다. ***
# DDL 만 적용하면 기존 work_schedules 행 수·값이 그대로이고 assignment 행도 생기지 않는다.
check("002: INSERT 구문 없음(자동 백필 제거 — 기존 월에 assignment 미생성)",
      re.search(r"\binsert\s+into\b", EXEC2) is None)
check("002: 테이블 UPDATE 구문 없음(schedule_assignment_id 자동 연결 제거)",
      re.search(r"\bupdate\s+public\.", EXEC2) is None
      and re.search(r"(?m)^\s*update\b", EXEC2) is None)
check("001+002: DELETE/TRUNCATE 없음(기존 행 삭제 불가)",
      re.search(r"\b(delete\s+from|truncate)\b", EXEC1 + EXEC2) is None)
check("002: users 현재 소속(u.department_id/u.team_id)을 참조하지 않음(과거 조 추정 금지)",
      "u.department_id" not in EXEC2 and "u.team_id" not in EXEC2
      and "from public.users" not in EXEC2)
check("002: work_schedules 를 데이터 소스로 읽지 않음(DDL 전용)",
      "from public.work_schedules" not in EXEC2)

# RLS: 002 는 001 과 동일 패턴(정책 없이 RLS enable → service_role 로만 접근)
check("002: 신규 테이블 RLS enable(001 과 동일 패턴)",
      "enable row level security" in EXEC2)

# 001↔002 기본 계약 정합 + FK 삭제 정책
check("001+002: 모든 FK 가 on delete restrict(연쇄 삭제/SET NULL 없음)",
      "on delete cascade" not in (EXEC1 + EXEC2)
      and "on delete set null" not in (EXEC1 + EXEC2))
check("002: PK 타입이 001 과 동일(bigint identity)",
      "bigint generated by default as identity primary key" in EXEC2)
check("002: created/updated_at 이 001 과 동일(timestamptz not null default now())",
      EXEC2.count("timestamptz not null default now()") >= 4)
check("002: 롤백 주석이 FK 의존성 역순(제약→인덱스→컬럼→assignments→shift_groups)",
      -1 < SQL2.find("drop constraint if exists work_schedules_assignment_date_key")
      < SQL2.find("drop index if exists work_schedules_assignment_idx")
      < SQL2.find("drop column if exists schedule_assignment_id")
      < SQL2.find("drop table if exists public.schedule_assignments")
      < SQL2.find("drop table if exists public.shift_groups"))
check("002: 기존 데이터 무백필 정책이 SQL 주석에 문서화됨",
      "자동 백필" in SQL2 and "fallback" in SQL2)


# ===== 2) validators 계약 ↔ 002 스키마 제약 정합 =====
print("validators 계약 <-> 002 스키마 정합")
from modules import validators  # noqa: E402

check("normalize_schedule_month((2027,7)) == 2027-07-01 (월 1일 CHECK 정합)",
      validators.normalize_schedule_month((2027, 7)) == "2027-07-01")
check("normalize_schedule_month('2027-07-19') == 2027-07-01",
      validators.normalize_schedule_month("2027-07-19") == "2027-07-01")

emp_nos = {"E1"}
